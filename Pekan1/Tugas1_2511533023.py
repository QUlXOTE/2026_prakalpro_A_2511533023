def main():
    # Input data dari pengguna
    A1_3023 = int(input("Input angka-1: "))
    A2_3023 = int(input("Input angka-2: "))

    # Operator Penjumlahan
    print("operator Penjumlahan")
    hasil_3023 = A1_3023 + A2_3023
    print("Hasil =", hasil_3023)

    # Operator Pengurangan
    print("operator Pengurangan")
    hasil_3023 = A1_3023 - A2_3023
    print("Hasil =", hasil_3023)

    # Operator Perkalian
    print("operator Perkalian")
    hasil_3023 = A1_3023 * A2_3023
    print("Hasil =", hasil_3023)

    # Operator Hasil Bagi (pembagian bulat)
    print("operator hasil bagi")
    hasil_3023 = A1_3023 // A2_3023  # Gunakan // untuk pembagian bulat seperti pada tipe data 'int' di Java
    print("Hasil =", hasil_3023)

    # Operator Sisa Bagi (Modulus)
    print("operator sisa bagi")
    hasil_3023 = A1_3023 % A2_3023
    print("Hasil =", hasil_3023)


if __name__ == "__main__":
    main()